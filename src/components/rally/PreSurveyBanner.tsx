import { ExternalLinkIcon } from "@/components/ui/icons";
import { EXTERNAL_LINKS, PRE_SURVEY_DISPLAY_HOST } from "@/lib/routes";
import type { RallyPhase } from "@/lib/rally";

/**
 * 참석 예비조사 배너 — `/rally-2026-08-28` 최상단 (디자인 스펙 §37 · 검증 §45).
 *
 * 사용자 지시(2026-08-26): 대회 **전**에 참석 가능 여부를 묻는 구글 폼으로 보내는 배너를 상단에 붙인다.
 *
 * ## ★★ 이름을 `AttendanceBanner` 로 바꾸지 마라 (§37.9)
 *
 * `QrAttendanceCard` 가 이미 «attendance» 를 점유했고, 이 페이지의 유일한 위험이
 * **«참석 조사» ↔ «QR 출석체크» 혼동**이다(§45-2). 코드 이름에서도 **«출석(attendance)»과
 * «조사(survey)»를 가른다** — 안 가르면 그 혼동이 **코드 레벨에서 재발**한다.
 *
 * ## ★★ 이 배너가 막는 사고 — 설명 줄이 게시 조건인 이유
 *
 * ```
 * 조합원이 배너를 누른다 → «참석합니다» 를 고르고 성함·사번을 낸다
 *   → «참석 등록 끝» 으로 읽는다 → 당일 QR 출석체크(1차·2차)를 건너뛴다
 *   → 금융노조 출석 기록이 남지 않는다
 * ```
 *
 * 둘 다 «참석» 등록이고 둘 다 노조가 받는다. 폼이 **성함·사번을 받는 절차**라
 * «등록을 마쳤다»로 읽히기 쉽고, 이 페이지는 지금까지 «참석»이라는 낱말을 **당일 출석**에만 써 왔다.
 * → **`당일 QR 출석체크는 따로 해야 합니다.` 는 §45-11 조건 1(«없으면 게시 불가»)이다.**
 * **배너 «안»에 둔다** — 해가 생기는 순간이 «누를 때»이므로 누르는 면 안에 있어야 한다.
 * ⚠ **`text-caption` 으로 낮추지 마라**(§37.3 근거 5): `WayfindingBlock` 의 보조 설명과 성격이 다르다.
 * 그 줄은 «링크가 무엇인지» 를 말하지만 이 줄은 **행동이 갈리는 사실**이다(§5.3 삭제 예외).
 *
 * ## ★★ `aria-label`·`title` 을 붙이지 마라 (§45-11 조건 10 · §37.13-2)
 *
 * 붙이는 순간 **위 문장이 링크 낭독에서 사라진다** — 링크 목록·탭 이동으로 훑는 스크린리더
 * 사용자가 **조건 1 의 문장을 듣지 못한 채 누른다.** 혼동을 막으려고 넣은 문장이
 * **그 위험에 가장 취약한 사용자에게만 없어진다.**
 * → **카드 전체가 단일 `<a>` 이고 내부 텍스트 세 줄이 접근성 이름을 이룬다**(QR 카드와 같은 규칙).
 *
 * ⚠ 두 속성은 **금지 결론이 같고 기전이 다르다**(§37.13-2 — 뒤집으려는 사람을 위해 적어 둔다).
 * accname 순서는 `aria-labelledby` → `aria-label` → 내용 → `title` 이라,
 * `aria-label` 은 **내용을 대체**하고 `title` 은 **이름을 못 덮는 대신 설명이 덧붙어** 세 줄이 네 조각이 된다.
 * 게다가 `title` 은 터치·키보드에서 **뜨지도 않는다.** *"`title` 은 이름을 안 덮는데?"* 로 금지를 뒤집지 마라.
 *
 * ⚠ **`<section aria-label>` 로 감싸지 마라**(§37.13-1 — 사이트 전수 실측).
 * 이 사이트 규칙은 **«화면에 헤딩이 있으면 `aria-labelledby`, 없으면 `aria-label`»** 이고,
 * 이 페이지의 지역 이름 5개는 **전부 화면의 `<h2>`** 다. 배너에 붙이면 **그 하나만 «화면에 없는 이름»** 이 된다.
 * 그리고 **랜드마크는 «건너뛸 단위»인데 카드 하나는 건너뛸 것이 없다.**
 * 래퍼 `<div>` 도 만들지 마라 — `mt-6` 은 `<a>` 에 직접 준다.
 *
 * ## 표면 — 흰 면 + 남색 «테두리». 채우지 마라 (§37.3)
 *
 * 이 페이지의 외부 링크 카드는 **무게가 3단으로 정렬**돼 있다:
 *
 * | 무게 | 표면 | 카드 |
 * |---|---|---|
 * | 1 (가장 무겁다) | 남색 **채운** 면 `bg-primary` | `QR 인증 바로 하기` — 당일 반드시 해야 하는 행동 |
 * | 2 | 흰 면 + `border-primary` | **이 배너** — 대회 전에 응답해 달라는 요청 |
 * | 3 | 흰 면 + `border-border-strong` | `네이버 지도로 길찾기` — 필요할 때 쓰는 도구 |
 *
 * ⚠⚠ **남색으로 채우지 마라.** *면과 문장이 어긋나면 조합원은 면을 믿는다*(§45-15(2)) —
 * 문안이 «따로 해야 합니다» 라고 정확히 말해도 **면이 «이것이 바로 그 행동이다» 라고 먼저 말한다.**
 * **혼동을 문안으로 막고 형태로 되살리는 셈**이 된다.
 * ⚠ **필 버튼 금지** — 이 프로젝트에서 필 버튼은 **페이지 안 조작**의 형태다(외부 이동은 카드 · §0.7).
 * ⚠ **`rounded-panel`(24px)로 키우지 마라**: 이 페이지에서 24px 은 **섹션 컨테이너 전용**이고
 * 바로 아래가 블록 1 패널(24px)이라 **«섹션이 둘 연속»으로 읽혀 «누르는 것»이라는 사실이 약해진다.**
 * 실측으로도 `rounded-panel`+`p-5` 는 대형 `18:30` 을 **6px 더 민다**(§37.2).
 *
 * ## 생애주기 — `past` 는 «숨김»이 아니라 «렌더 금지»다 (§37.6)
 *
 * ★ **`RallyBanner` 를 근거로 «이 프로젝트는 배너를 숨기지 않고 낮춘다» 로 일반화하지 마라.**
 * 가르는 것은 표면이 아니라 **그 면이 «입구»인가 «행동 요청»인가**다(§45-15(4)):
 * `RallyBanner` 는 **안내 페이지로 가는 입구**라 `past` 에도 참이지만,
 * 이 배너는 **행동을 요청한다** — 지난 대회의 «참석 예비조사» 배너는 조합원에게
 * «아직 참석 신청을 받는다»로 읽혀 **거짓이 된다.**
 * 판정을 **호출부가 아니라 컴포넌트 안**에 두는 이유: **어디에 갖다 붙여도 거짓이 될 수 없게** 하려는 것이다
 * (`WayfindingBlock` 이 *"교통 안내 없는 링크를 만들 방법 자체를 없앤다"* 로 규율을 구조로 바꾼 것과 같은 패턴).
 * «지워진 자리» 문제는 없다 — `past` 에는 `RALLY_PAST_NOTE` 가 `h1` 바로 아래에 이미 뜬다.
 *
 * 날짜 계산은 호출부가 `rallyPhase()` 로 넘긴다(`RallyBanner` 패턴) — **컴포넌트는 시간을 모른다.**
 */
export function PreSurveyBanner({ phase }: { phase: RallyPhase }) {
  /* 조건 5 — 렌더 자체를 하지 않는다. `hidden`·`display:none` 이 아니다 */
  if (phase === "past") return null;

  return (
    /*
      `today` 무게 낮춤 — **테두리 색 하나만** 바꾼다(§37.5).

      ★★ **글자를 한 글자도 건드리지 마라.** 낮춰야 하는 것은 «주목»이지 «판독»이 아니다.
      혼동 위험은 **당일에 최고조**인데(§45-6), 바로 그날 `당일 QR 출석체크는 따로 해야 합니다.` 를
      작게·흐리게 만드는 것은 **정확히 반대 방향**이다.
      → 크기·색·굵기·`opacity` 를 낮추는 안, 배지 추가, 접기(`<details>`), 자리 이동 **전부 기각**이다
        (배지·`<h2>` 는 **높이를 늘려** 대형 `18:30` 의 `today` 여유 30px 을 먹는다 — §37.2 실측).
      ⚠ **`border-border-soft`(#e5e7eb · 1.24)로 낮추지 마라** — UI 경계 3:1 미달이다.
        `border-border-strong`(#6b7280 · **4.83**)이 **낮출 수 있는 하한**이다(`RallyBanner` 와 같은 규칙).
      ⚠ **`today` 에서 «지난 일»로 보이게 하지 마라** — 폼은 당일에도 유효하다. `완료` 배지·취소선 금지.
      ⚠ **hover·focus 링은 `today` 에서도 `primary` 그대로다** — 포커스 링은 **접근성 요소**이지 «무게»의 축이 아니다.
      ⚠ **`hover:border-2` 로 바꾸지 마라** — `border` 는 박스 크기에 포함돼 **레이아웃이 1px 흔들린다.**
        굵어 보이는 효과는 바깥에 얹히는 `hover:outline-2` 가 낸다.
    */
    <a
      href={EXTERNAL_LINKS.preSurvey}
      target="_blank"
      rel="noopener noreferrer"
      className={`rounded-card ease-out-soft group mt-6 block border bg-bg p-4 transition-colors duration-150 hover:outline-2 hover:outline-primary focus-visible:outline-3 focus-visible:outline-primary focus-visible:outline-offset-2 ${phase === "today" ? "border-border-strong" : "border-primary"}`}
    >
      {/*
        제목 — 축자 문면(§45-10(1) · 사용자 지정). `예비` 는 폼 제목에 없는 낱말이지만
        **사실과 부합하고**(대회 전 · `참석할 수 있으신가요?` · 당일 «참석명단 작성»이 따로 있다)
        ★ **낱말 자체가 «본 절차가 따로 있다»를 함의해 혼동을 푸는 데 기여한다**(§45-3).
        ⚠ **`참석 등록`·`참석 신청`·`사전 등록`·`참가 신청` 으로 바꾸지 마라** — 혼동을 **정확히 반대 방향**으로 민다.
        폼이 스스로를 `참석 조사`·`참석여부 조사` 라 부른다.
        ⚠ **`text-lead` 로 키우지 마라**(조건 7): QR 카드 제목과 같은 급이 된다.
        설명 줄과 **크기가 같은 것이 설계값**이고, 위계는 **굵기(700↔400)와 색(primary↔ink)** 이 진다.
        **↗ 를 텍스트 문자로 쓰지 마라** — 서체마다 위치·크기가 튄다(SVG 재사용).

        ★ **`break-words` 는 «지금 넘쳐서»가 아니라 «규율과 측정이 엇갈려서» 붙였다**(2026-08-26).
        QA 사전 실측으로는 이 줄과 아래 줄 모두 슬롯 216·201·161 **초과 0** 인데,
        디자이너 §38.1 은 카드 안(`p-4`) `break-keep` 단독 한계를 **4자**로 잡고 아래 줄에 `출석체크는`(**5자**)이 있다.
        **어느 쪽이 맞든 `break-words` 면 둘 다 만족**하고, 안 넘치는 줄에서 **높이 변화는 0**(QA 실측)이다.
        → **판정선은 «슬롯 초과 0» 이지 특정 클래스가 아니다.** 클래스를 근거로 반려·강제하지 마라.
      */}
      <span className="block break-keep break-words text-body font-bold text-primary group-hover:underline">
        참석 예비조사
        <ExternalLinkIcon className="ml-1 inline size-4 align-[-2px]" />
      </span>

      {/*
        ★★ **게시 조건 1 — 이 줄을 지우면 게시 불가다**(§45-10(2) 축자 · 파일 상단 주석의 «막는 사고»).
        ⚠ **`별개입니다` 로 바꾸지 마라** — 그것은 관계만 말하고 **행동을 말하지 않는다.**
        ⚠ **`당일` 을 빼지 마라** — 이 조사와 **시점이 다르다**는 것이 혼동의 핵심이다.
        ⚠ **`※` 를 붙이지 마라** — 단서가 아니라 **카드 본문**이고, 이 페이지는 `※` 개수를 센다.
        `QR 출석체크` 는 블록 2-A 제목(`QR 출석체크 안내`)의 **용어 재사용**이라 창작 0 이다.

        ★★ **이 줄에 `break-all` 을 쓰지 마라 — `QR` 이 온다.**
        `break-all` 은 **넘치지도 않는 `QR`·`LED`·`KDB`·`SC` 를 아무 데서나 끊는다.**
        여기서 `QR` 이 `Q/R` 로 갈리면 **미관 문제로 끝나지 않는다** — 그 두 글자가 출석 경로를 가리키는 낱말이다.
        **한글 줄의 처방은 `break-keep break-words`** 이고, `break-all` 은 **도메인 줄 하나**에만 쓴다(§38.2).
      */}
      <span className="mt-1 block break-keep break-words text-body text-ink">
        당일 QR 출석체크는 따로 해야 합니다.
      </span>

      {/*
        도메인 줄 — 외부 이동 **3중 병행**(§14.1): ↗ 아이콘 + 도메인 표기 + 접근성 이름.
        배너 이름과 도착 페이지 제목이 **글자가 달라** «다른 곳에 왔나» 를 막는 장치다(조건 3).

        ★★ **`break-all` 이다**(리더 확정 — **이 프로젝트의 선례 승계**: 온누리·QR·길찾기 카드가 전부
        도메인 줄에 `break-all` 을 쓴다. **선례 승계 = 창작 0**).
        ⚠ **«`break-all` 만이 유일한 처방»은 틀렸다**(리더 정정 2026-08-26): `break-words` 도 라틴 낱말을 끊는다.
        **판정선은 «슬롯 초과 0» 이지 특정 클래스가 아니다** — 클래스 이름을 근거로 반려·강제하지 마라.
        `keep-all` 은 **CJK 규칙**이라 `docs.google.com` 같은 **라틴 낱말을 끊지 않는다** — 그것만 참이다(§38.2).
        한글은 `break-keep break-words`, 라틴·도메인은 `break-all`. 위 두 줄과 이 줄이 다른 이유가 그것이다.

        ⚠⚠ **이 줄에서 처방을 빼려는 사람에게 — 슬롯을 «배너 바깥»으로 재지 마라.**
        QA 부록 D 는 «카드 밖» 슬롯을 **281**(360·sb15)로 준다. 그런데 **이 줄은 배너 자신의 `p-4` 안**에 있어
        실제 가용 폭은 **281 − 패딩 양쪽 ≈ 215** 다(디자이너 §37.7 이 그 값으로 쟀고, 이 문자열의
        `width:0` 폭 **231** → **16px 초과**를 냈다). **같은 «281»이 두 계약을 가리킨다** —
        «배너가 차지하는 폭»과 «배너 «안»에서 글자가 쓸 수 있는 폭»은 다르다.
        → **처방을 지우려면 이 줄이 놓인 상자에서 `scrollWidth − clientWidth` 를 직접 재라.**
        ⚠ **`truncate`(말줄임)로 바꾸지 마라** — 주소가 잘리면 표기하는 의미가 사라진다.
        이 페이지의 세 카드(온누리·QR·길찾기)가 전부 같은 이유로 `break-all` 을 쓴다.
      */}
      <span className="mt-1.5 block break-all text-caption text-ink-muted">
        외부 링크(새 창) · {PRE_SURVEY_DISPLAY_HOST}
      </span>
    </a>
  );
}
