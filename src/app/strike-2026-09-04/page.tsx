function TimeText({ value }: { value: string }) {
  const i = value.search(/[-~]/);
  // `15:15` 단독 행 — **구분자를 붙이지 마라**(검증 조건 8). 원문은 폐회선언 시각만 말한다
  if (i < 0) return <>{value}</>;
  return (
    <>
      {value.slice(0, i + 1)}
      <wbr />
      {value.slice(i + 1)}
    </>
  );
}

